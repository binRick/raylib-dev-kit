#!/usr/bin/env python3
"""Regenerate the example's placeholder assets: a few synthesised sounds and three lathe-turned
models (OBJ + MTL). No dependencies. They exist so the example has real files to list."""
import math, pathlib, struct, wave

out = pathlib.Path(__file__).resolve().parent.parent / "example" / "assets"
out.mkdir(parents=True, exist_ok=True)

def tone(name, notes, dur, noise=0.0, vol=0.5):
    rate, frames, seed, n = 44100, [], 12345, int(44100 * dur)
    for i in range(n):
        t = i / rate
        f = notes[min(len(notes) - 1, int(len(notes) * i / n))]
        env = min(1, t * 80) * (1 - i / n) ** 2
        seed = (seed * 1103515245 + 12345) & 0x7FFFFFFF
        v = math.sin(2 * math.pi * f * t) * (1 - noise) + (seed / 0x3FFFFFFF - 1) * noise
        frames.append(struct.pack("<h", int(v * env * vol * 32767)))
    with wave.open(str(out / name), "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(rate); w.writeframes(b"".join(frames))

tone("jump.wav", [330, 440, 660], 0.18)
tone("land.wav", [140, 90], 0.14, noise=0.5)
tone("coin.wav", [988, 1319], 0.28)
tone("door_open.wav", [110, 147, 196, 147], 0.55, noise=0.25)
tone("click.wav", [1200], 0.05)
tone("alarm.wav", [660, 520, 660, 520, 660, 520], 0.9, vol=0.35)
tone("wind.wav", [60], 1.6, noise=0.92, vol=0.3)

def lathe(name, profile, bands, segs=28):
    """profile: (radius, height) points bottom to top. bands: (material, rgb) per profile span."""
    v, vn, faces = [], [], []
    for j, (r, y) in enumerate(profile):
        a, b = profile[max(j - 1, 0)], profile[min(j + 1, len(profile) - 1)]
        dr, dy = b[0] - a[0], b[1] - a[1]
        ln = math.hypot(dr, dy) or 1
        for i in range(segs):
            t = 2 * math.pi * i / segs
            v.append((r * math.cos(t), y, r * math.sin(t)))
            vn.append((dy / ln * math.cos(t), -dr / ln, dy / ln * math.sin(t)))
    lines = [f"# {name}: generated by scripts/gen-assets.py", f"mtllib {name}.mtl"]
    lines += [f"v {x:.4f} {y:.4f} {z:.4f}" for x, y, z in v]
    lines += [f"vn {x:.4f} {y:.4f} {z:.4f}" for x, y, z in vn]
    for j in range(len(profile) - 1):
        lines.append(f"usemtl {bands[j][0]}")
        for i in range(segs):
            a, b = j * segs + i + 1, j * segs + (i + 1) % segs + 1
            c, d = a + segs, b + segs
            lines += [f"f {a}//{a} {c}//{c} {b}//{b}", f"f {b}//{b} {c}//{c} {d}//{d}"]
    (out / f"{name}.obj").write_text("\n".join(lines) + "\n")
    seen, mtl = set(), []
    for m, (r, g, b) in bands:
        if m in seen: continue
        seen.add(m)
        mtl += [f"newmtl {m}", f"Kd {r/255:.3f} {g/255:.3f} {b/255:.3f}", "Ka 0 0 0", "Ks 0 0 0", ""]
    (out / f"{name}.mtl").write_text("\n".join(mtl))

W, R, C, G, D = ("white", (236, 240, 255)), ("red", (240, 84, 104)), ("cyan", (120, 225, 235)), ("gold", (255, 205, 80)), ("dark", (60, 66, 100))
lathe("rocket", [(0.0, 0.0), (0.34, 0.0), (0.2, 0.25), (0.42, 0.3), (0.42, 1.7), (0.36, 2.1), (0.2, 2.5), (0.0, 2.75)], [D, D, R, W, C, R, R])
lathe("lighthouse", [(0.0, 0.0), (0.7, 0.0), (0.62, 0.6), (0.54, 1.2), (0.46, 1.8), (0.4, 2.3), (0.56, 2.32), (0.56, 2.42), (0.32, 2.44), (0.32, 2.85), (0.48, 2.87), (0.0, 3.25)],
      [D, W, R, W, R, D, D, D, G, D, R])
lathe("vase", [(0.0, 0.0), (0.3, 0.0), (0.55, 0.45), (0.6, 0.9), (0.42, 1.35), (0.22, 1.65), (0.3, 1.95), (0.36, 2.0), (0.26, 1.98)], [D, C, C, G, C, C, G, D])
print("wrote", sorted(p.name for p in out.iterdir()))
